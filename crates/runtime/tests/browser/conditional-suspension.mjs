import assert from 'node:assert/strict';
export async function conditionalSuspensionSmoke(directory) {
  const { suspendWhenNeeded } = await import(new URL('./conditional-suspension.js', directory));
  let calls = 0, pending;
  const checkpoint = suspendWhenNeeded(() => { calls++; return pending; });
  const run = WebAssembly.promising(checkpoint);
  await run(); assert.equal(calls, 1);
  let resumed = false;
  pending = new Promise(resolve => setTimeout(() => { resumed = true; resolve(); }, 5));
  await run(); assert.ok(resumed); assert.equal(calls, 2);
  pending = Promise.reject(new Error('failed wait'));
  await assert.rejects(run(), /failed wait/);
  pending = undefined;
  await run(); assert.equal(calls, 4, 'rejected waits must release pending state');
  const throwing = suspendWhenNeeded(() => { throw new Error('aborted checkpoint'); });
  await assert.rejects(WebAssembly.promising(throwing)(), /aborted checkpoint/);
  let resolveFirst, resolveSecond;
  pending = new Promise(resolve => { resolveFirst = resolve; });
  const first = run();
  pending = new Promise(resolve => { resolveSecond = resolve; });
  const second = run();
  resolveSecond(); await second; resolveFirst(); await first;
  assert.equal(calls, 6, 'concurrent suspended stacks retain their own Promise');
  const { createScheduler } = await import(new URL('./scheduler.js', directory));
  const controller = new AbortController(); controller.abort(new Error('stopped'));
  assert.throws(() => createScheduler(controller.signal).run(checkpoint), /stopped/);
  const paced = createScheduler();
  let inputRan = false;
  setTimeout(() => { inputRan = true; }, 0);
  paced.deferFrame(4);
  await paced.run(paced.checkpoint, 0x401000);
  assert.ok(inputRan, 'foreground pacing must allow input/timers to run');
  assert.equal(paced.pacedYields, 1);
  assert.ok(paced.suspendedMs >= paced.pacedMs);
  assert.throws(() => paced.deferFrame(-1), RangeError);
  const stopped = new AbortController();
  const cancelled = createScheduler(stopped.signal);
  cancelled.deferFrame(16);
  const waiting = cancelled.run(cancelled.checkpoint, 0x401000);
  stopped.abort(new Error('cancel paced frame'));
  await assert.rejects(waiting, /cancel paced frame/);
  console.log('Conditional checkpoints: synchronous path, real waits, rejection, concurrent stacks and cancellation passed');
}
